/**
 * Looks up the suggestion list for a department by its `dept_abbreviation`.
 * Returns an empty array if the department has no suggestions on file yet
 * (e.g. MCTC, MLGOO, PNP, BFP, LEIPO) — safe to call unconditionally.
 */
export function getSuggestedPositions(deptAbbreviation?: string | null): SuggestedPlantillaPosition[] {
  if (!deptAbbreviation) return [];
  return DEPARTMENT_PLANTILLA_SUGGESTIONS[deptAbbreviation] ?? [];
}

/** How many of `title` are allowed in `deptAbbreviation`, per the org chart. */
export function getMaxAllowedForPosition(deptAbbreviation: string | null | undefined, title: string): number {
  const entry = getSuggestedPositions(deptAbbreviation).find(p => p.title === title);
  return entry?.max ?? 1;
}
